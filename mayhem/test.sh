#!/usr/bin/env bash
#
# mayhem/test.sh — RUN the graded pudconvert binary (/mayhem/pudconvert, mayhem/build.sh's step 2)
# on KNOWN .pud maps and assert KNOWN output values decoded from the resulting Stratagus .smp/.sms
# Lua files. wargus ships no upstream unit-test suite (no CTest/gtest target for pud.cpp — only
# StormLib's own vendored tests, which are unrelated), so this is a from-scratch behavioral oracle
# rather than a ported one.
#
# WHICH BINARIES (issue #1460 A): the oracle runs the graded binaries themselves, never a separate
# test build. /mayhem/pudconvert is the very binary the `pudconvert` target fuzzes. Every fixture is
# also decoded by /mayhem/fuzz_Parse, the very binary the `parse` target fuzzes, in its dump mode
# (mayhem/fuzz_Parse.cpp): each check of a fixture passes only if that decode is exactly what
# pudconvert wrote (and the garbage input must be rejected there too). Both binaries link the one
# pud.o that mayhem/build.sh compiles with the graded flags (-O0, ASan+UBSan, SanitizerCoverage).
# This suite used to run a separate -O2, unsanitized build, and a pud.cpp patch gated on that
# difference (`#ifndef __OPTIMIZE__ return false;`, or the same with `__has_feature(address_sanitizer)`)
# cleared every PoV while it stayed 18/18. A separately compiled Parse-entry TU was not enough either:
# a pud.h/pud.cpp patch could key on that TU's own context (FuzzedDataProvider.h's header guard,
# __BASE_FILE__) or on a symbol only the harness links, and switch Parse off only in fuzz_Parse. Now
# no compile-time or link-time property separates the code checked here from the code the PoVs replay
# against. What does differ is the run itself (the dump variable, argv, the input bytes); a patch
# keyed on those is not closed off by this suite. The 100-byte maps reach Parse in fuzz_Parse exactly
# as fuzzing passes them; the two larger maps are parsed whole there, as pudconvert parses them.
# Every fixture converts cleanly under the sanitizers, and both binaries are leak-free on them, so a
# sanitizer report here is a real failure of the program under test.
#
# Fixture: mayhem/pudconvert/testsuite/farscape2006.pud (also a fuzz seed) is the ONLY .pud file
# wargus ships in-tree (maps/skirmish/multiplayer/(8)farscape2006.pud). Golden values below were
# read directly off this file's own header/body content (map name "Left Verse Right", 96x96, 8
# active players, 9216 tiles, 88 placed non-start units) via an unmodified local build — NOT
# invented — and re-confirmed here by decompressing pudconvert's real output. A sabotaged/no-op
# PudData::Parse (e.g. patched to always "succeed" without filling fields, or main() short-
# circuited to exit(0) before conversion) will emit an empty/absent/garbled PresentMap(...) line,
# a wrong tile/unit count, or no output files at all -- any of which fails the assertions below.
#
# Small maps (QA #1131): three hand-built maps, regenerated byte for byte by
# mayhem/gen_pud_inputs.py -- mayhem/parse/testsuite/map100.pud and named100.pud (EXACTLY 100 bytes
# each, the only length the `parse` harness ever passes to PudData::Parse) and
# mayhem/pudconvert/testsuite/twokeeps.pud (464 bytes). farscape2006.pud alone is 72,102 bytes, so
# without these the suite could not see a patch that makes Parse reject every short buffer (e.g.
# `if (size < 716) return false;`): that makes every crash input go away without fixing any bounds
# check, while leaving the farscape assertions green. Every section in these maps has the length
# the in-tree spec doc/pud-specs.txt gives it -- TYPE 16 ("WAR2 MAP\0" + 7-byte id tag, the same
# layout as farscape2006.pud and every map under maps/), DESC 32, OWNR/SIDE/AIPL 16, SGLD/SLBR/SOIL
# 32, ERA 2, DIM 4, MTXM/SQM/REGM 2*X*Y, OILM X*Y, UNIT 8*n -- so a patch that enforces those
# lengths still passes. What these maps cannot be is full-size: the in-tree maps are 64..128 tiles
# square and also carry the UDTA/UGRD sections (thousands of bytes; the spec marks both optional),
# and a 100-byte map only has room for a few sections (map100 has no VER/DESC, named100 no
# VER/OWNR). So these checks pin upstream's acceptance of small, internally consistent maps, not a
# strict "every section present" validator. They assert only values DECODED from the fixture bytes
# (player types, name, dimensions, tileset, tiles and wall flags, units, start positions and
# resources), never defaults of sections a fixture leaves out. Golden values were taken from the
# unmodified build.
#
# Output goes to /tmp (never under /mayhem, which is read-only during Mayhem's coverage
# collection) -- same rule the Mayhemfile cmd lines follow.
set -uo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${MAYHEM_JOBS:=$(nproc)}"
cd "$SRC"

# emit_ctrf <tool> <passed> <failed> [skipped] [pending] [other]
emit_ctrf() {
  local tool="$1" passed="$2" failed="$3" skipped="${4:-0}" pending="${5:-0}" other="${6:-0}"
  local tests=$(( passed + failed + skipped + pending + other ))
  cat > "${CTRF_REPORT:-$SRC/ctrf-report.json}" <<JSON
{
  "results": {
    "tool": { "name": "$tool" },
    "summary": {
      "tests": $tests,
      "passed": $passed,
      "failed": $failed,
      "pending": $pending,
      "skipped": $skipped,
      "other": $other
    }
  }
}
JSON
  printf 'CTRF {"results":{"tool":{"name":"%s"},"summary":{"tests":%d,"passed":%d,"failed":%d,"pending":%d,"skipped":%d,"other":%d}}}\n' \
    "$tool" "$tests" "$passed" "$failed" "$pending" "$skipped" "$other"
  [ "$failed" -eq 0 ]
}

RUNNER=/mayhem/pudconvert
if [ ! -x "$RUNNER" ]; then
  echo "ERROR: $RUNNER not found -- mayhem/build.sh should have produced it (step 2)" >&2
  emit_ctrf "wargus-pud-oracle" 0 1
  exit $?
fi

FIXTURE="$SRC/mayhem/pudconvert/testsuite/farscape2006.pud"
OUTDIR="$(mktemp -d /tmp/wargus-test.XXXXXX)"
trap 'rm -rf "$OUTDIR"' EXIT

passed=0
failed=0
fail() { echo "FAIL: $1" >&2; failed=$((failed + 1)); }
# The `parse` target's entry (issue #1460 A; see the header): every fixture is ALSO decoded by
# /mayhem/fuzz_Parse itself, in the harness's dump mode. ENTRY_ERR holds why that entry disagrees with
# pudconvert on the fixture being checked; while it is set, every check of that fixture fails with it,
# so each check below holds on both graded binaries, not only on pudconvert.
PARSE_ENTRY=/mayhem/fuzz_Parse
ENTRY_ERR=""
ok()   { if [ -n "$ENTRY_ERR" ]; then fail "$ENTRY_ERR"; else passed=$((passed + 1)); fi; }
# parse_entry <input> <out.gz> <log> <err>: run fuzz_Parse on <input> once in dump mode (libFuzzer
# executes that one file and exits); prints its exit code.
parse_entry() {
  local rc=0
  WARGUS_PARSE_ORACLE_OUT="$2" "$PARSE_ENTRY" "$1" >"$3" 2>"$4" || rc=$?
  echo "$rc"
}
# check_entry <fixture> <name> <dir>: the parse entry decodes <fixture> to exactly what pudconvert
# wrote to <dir>/<name>.smp.gz + <dir>/<name>.sms.gz (whose content the checks below pin).
check_entry() {
  local fx="$1" name="$2" d="$3" rc want got
  ENTRY_ERR=""
  if [ ! -x "$PARSE_ENTRY" ]; then
    ENTRY_ERR="$name: $PARSE_ENTRY not found -- mayhem/build.sh should have produced it (step 1)"
    return
  fi
  rc="$(parse_entry "$fx" "$d/$name.entry.gz" "$d/$name.entry.log" "$d/$name.entry.err")"
  want="$( { zcat "$d/$name.smp.gz" && zcat "$d/$name.sms.gz"; } 2>/dev/null || true)"
  got="$(zcat "$d/$name.entry.gz" 2>/dev/null || true)"
  if [ "$rc" -ne 0 ] || [ -z "$got" ] || [ "$got" != "$want" ]; then
    ENTRY_ERR="$name: the parse target's binary ($PARSE_ENTRY) does not decode it as pudconvert does (rc=$rc, stdout: $(head -c 80 "$d/$name.entry.log" | tr '\n' '|'), stderr: $(tail -c 160 "$d/$name.entry.err" | tr '\n' '|'))"
  fi
}

# --- run the conversion (known input) ---
rc=0
"$RUNNER" "$FIXTURE" "$OUTDIR" >"$OUTDIR/stdout.log" 2>"$OUTDIR/stderr.log" || rc=$?
check_entry "$FIXTURE" farscape2006 "$OUTDIR"
if [ "$rc" -eq 0 ]; then
  ok
else
  fail "pudconvert exited non-zero on a known-good .pud file (rc=$rc), see $OUTDIR/stderr.log"
fi

SMP="$OUTDIR/farscape2006.smp.gz"
SMS="$OUTDIR/farscape2006.sms.gz"

# --- assert 1: both output files exist ---
if [ -s "$SMP" ] && [ -s "$SMS" ]; then
  ok
else
  fail "expected output files missing/empty: $SMP / $SMS"
fi

# --- assert 2: the PresentMap(...) line carries the EXACT known map name/player-count/dims ---
# Known-good line (confirmed via an unmodified local build): PresentMap("Left Verse Right", 8, 96, 96, 1)
if [ -f "$SMP" ]; then
  PRESENT_LINE="$(zcat "$SMP" 2>/dev/null | grep -F 'PresentMap(' || true)"
  if [ "$PRESENT_LINE" = 'PresentMap("Left Verse Right", 8, 96, 96, 1)' ]; then
    ok
  else
    fail "PresentMap(...) line mismatch -- got: [$PRESENT_LINE], want: PresentMap(\"Left Verse Right\", 8, 96, 96, 1)"
  fi
else
  fail "cannot check PresentMap(...) -- $SMP missing"
fi

# --- assert 3: known tile count (96*96 = 9216 SetTile(...) calls) ---
if [ -f "$SMS" ]; then
  TILE_COUNT="$(zcat "$SMS" 2>/dev/null | grep -c 'SetTile(' || true)"
  if [ "$TILE_COUNT" = "9216" ]; then
    ok
  else
    fail "SetTile(...) count mismatch -- got: $TILE_COUNT, want: 9216"
  fi
else
  fail "cannot check tile count -- $SMS missing"
fi

# --- assert 4: known placed-unit count (88 non-start CreateUnit(...) calls) ---
if [ -f "$SMS" ]; then
  UNIT_COUNT="$(zcat "$SMS" 2>/dev/null | grep -c 'CreateUnit(' || true)"
  if [ "$UNIT_COUNT" = "88" ]; then
    ok
  else
    fail "CreateUnit(...) count mismatch -- got: $UNIT_COUNT, want: 88"
  fi
else
  fail "cannot check unit count -- $SMS missing"
fi

# --- assert 5: invalid/truncated input is REJECTED (not silently "succeeded") ---
# Confirms the oracle isn't fooled by a Parse() sabotaged to always return true: PudToStratagus()
# calls exit(-1) on invalid pud data, so pudconvert must exit non-zero here.
# The parse entry must reject it too: PARSE-FAILED, and no decoded output. (The input is 32 bytes, so
# fuzz_Parse copies it into its 100-byte buffer exactly as fuzzing does; Parse rejects it on the first
# section header, which lies in those 32 bytes.)
BADFILE="$OUTDIR/not-a-pud-file"
printf 'this is definitely not a pud map' > "$BADFILE"
ENTRY_ERR=""
if [ ! -x "$PARSE_ENTRY" ]; then
  ENTRY_ERR="garbage input: $PARSE_ENTRY not found -- mayhem/build.sh should have produced it (step 1)"
else
  rc="$(parse_entry "$BADFILE" "$OUTDIR/garbage.entry.gz" "$OUTDIR/garbage.entry.log" "$OUTDIR/garbage.entry.err")"
  if [ "$rc" -ne 0 ] || ! grep -qx 'PARSE-FAILED' "$OUTDIR/garbage.entry.log" || [ -e "$OUTDIR/garbage.entry.gz" ]; then
    ENTRY_ERR="garbage input: the parse target's binary ($PARSE_ENTRY) did not reject it (rc=$rc, stdout: $(head -c 80 "$OUTDIR/garbage.entry.log" | tr '\n' '|'))"
  fi
fi
if "$RUNNER" "$BADFILE" "$OUTDIR" >/dev/null 2>&1; then
  fail "pudconvert accepted garbage input as valid (expected non-zero exit)"
else
  ok
fi

# --- small maps (see the header): 12 more tests ---
# convert_small <fixture> <name>: the known-good small map converts (rc=0, both outputs written), and
# check_entry decides whether the parse entry agrees, for this and the following checks of the map.
convert_small() {
  local fx="$1" name="$2" d="$OUTDIR/$2" rc=0
  mkdir -p "$d"
  "$RUNNER" "$fx" "$d" >"$d/stdout.log" 2>"$d/stderr.log" || rc=$?
  check_entry "$fx" "$name" "$d"
  if [ "$rc" -eq 0 ] && [ -s "$d/$name.smp.gz" ] && [ -s "$d/$name.sms.gz" ]; then
    ok
  else
    fail "$name: pudconvert failed on a known-good small map (rc=$rc, stderr: $(head -c 200 "$d/stderr.log"))"
  fi
}
# expect_lines <label> <.gz output> <grep -E pattern> <expected lines>: the matching lines, in order,
# are exactly the expected ones.
expect_lines() {
  local label="$1" gz="$2" pat="$3" want="$4" got
  if [ ! -s "$gz" ]; then fail "$label: cannot check -- $gz missing"; return; fi
  got="$(zcat "$gz" 2>/dev/null | grep -E "$pat" || true)"
  if [ "$got" = "$want" ]; then
    ok
  else
    fail "$label mismatch -- got: [$(printf '%s' "$got" | tr '\n' '|')], want: [$(printf '%s' "$want" | tr '\n' '|')]"
  fi
}
PT_NOBODY13='"nobody","nobody","nobody","nobody","nobody","nobody","nobody","nobody","nobody","nobody","nobody","nobody","nobody"'

# map100.pud (100 B): OWNR person/computer/13x nobody/neutral, ERA winter, DIM 3x1, three MTXM tiles
# (plain, orc wall, human wall), one neutral gold mine with Data 4.
# It has no DESC section, so the map name is not asserted.
M="$OUTDIR/map100"
convert_small "$SRC/mayhem/parse/testsuite/map100.pud" map100
WANT_PT="DefinePlayerTypes(\"person\",\"computer\",$PT_NOBODY13,\"neutral\")"
GOT_PT="$(zcat "$M/map100.smp.gz" 2>/dev/null | grep -E '^DefinePlayerTypes\(' || true)"
GOT_PM="$(zcat "$M/map100.smp.gz" 2>/dev/null | grep -E '^PresentMap\(' || true)"
if [ "$GOT_PT" = "$WANT_PT" ] && [[ "$GOT_PM" =~ ^PresentMap\(\".*\",\ 2,\ 3,\ 1,\ 1\)$ ]]; then
  ok
else
  fail "map100 player types + map header -- got: [$GOT_PT | $GOT_PM], want: [$WANT_PT | PresentMap(\"<any>\", 2, 3, 1, 1)]"
fi
expect_lines "map100 tileset + tiles" "$M/map100.sms.gz" '^(LoadTileModels|SetTile)\(' \
'LoadTileModels("scripts/tilesets/winter.lua")
SetTile(80, 0, 0, 0)
SetTile(163, 1, 0, 40)
SetTile(147, 2, 0, 40)'
expect_lines "map100 units" "$M/map100.sms.gz" '^(unit = CreateUnit|SetResourcesHeld)\(' \
'unit = CreateUnit("unit-gold-mine", 15, {2, 0})
SetResourcesHeld(unit, 10000)'

# named100.pud (100 B): DESC "Tiny Isle", ERA swamp, DIM 1x3, three MTXM tiles (orc wall, plain, human
# wall 0x08xx). No OWNR section fits next to DESC + DIM + MTXM in 100 bytes, so the player count (an
# upstream default) is not asserted.
M="$OUTDIR/named100"
convert_small "$SRC/mayhem/parse/testsuite/named100.pud" named100
GOT_PM="$(zcat "$M/named100.smp.gz" 2>/dev/null | grep -E '^PresentMap\(' || true)"
if [[ "$GOT_PM" =~ ^PresentMap\(\"Tiny\ Isle\",\ [0-9]+,\ 1,\ 3,\ 1\)$ ]]; then
  ok
else
  fail "named100 map header -- got: [$GOT_PM], want: PresentMap(\"Tiny Isle\", <n>, 1, 3, 1)"
fi
expect_lines "named100 tileset + tiles" "$M/named100.sms.gz" '^(LoadTileModels|SetTile)\(' \
'LoadTileModels("scripts/tilesets/swamp.lua")
SetTile(196, 0, 0, 40)
SetTile(80, 0, 1, 0)
SetTile(2049, 0, 2, 40)'

# twokeeps.pud (464 B): DESC "Two Keeps", same OWNR, ERA wasteland, DIM 4x4, SIDE human/orc, per-player
# SGLD/SLBR/SOIL/AIPL, 16 MTXM tiles, UNIT = human start (1,0) for player 0, orc start (3,3) for
# player 1, and a neutral gold mine with Data 6.
M="$OUTDIR/twokeeps"
convert_small "$SRC/mayhem/pudconvert/testsuite/twokeeps.pud" twokeeps
expect_lines "twokeeps player types + map header" "$M/twokeeps.smp.gz" '^(DefinePlayerTypes|PresentMap)\(' \
"DefinePlayerTypes(\"person\",\"computer\",$PT_NOBODY13,\"neutral\")
PresentMap(\"Two Keeps\", 2, 4, 4, 1)"
expect_lines "twokeeps player setup" "$M/twokeeps.sms.gz" '^(SetStartView|SetPlayerData|SetAiType)\((0|1),' \
'SetStartView(0, 1, 0)
SetPlayerData(0, "Resources", "gold", 2000)
SetPlayerData(0, "Resources", "wood", 1000)
SetPlayerData(0, "Resources", "oil", 500)
SetPlayerData(0, "RaceName", "human")
SetAiType(0, "wc2-land-attack")
SetStartView(1, 3, 3)
SetPlayerData(1, "Resources", "gold", 1500)
SetPlayerData(1, "Resources", "wood", 800)
SetPlayerData(1, "Resources", "oil", 300)
SetPlayerData(1, "RaceName", "orc")
SetAiType(1, "wc2-passive")'
expect_lines "twokeeps tileset + tiles" "$M/twokeeps.sms.gz" '^(LoadTileModels|SetTile)\(' \
'LoadTileModels("scripts/tilesets/wasteland.lua")
SetTile(80, 0, 0, 0)
SetTile(81, 1, 0, 0)
SetTile(82, 2, 0, 0)
SetTile(83, 3, 0, 0)
SetTile(163, 0, 1, 40)
SetTile(180, 1, 1, 40)
SetTile(147, 2, 1, 40)
SetTile(17, 3, 1, 0)
SetTile(2049, 0, 2, 40)
SetTile(2306, 1, 2, 40)
SetTile(197, 2, 2, 40)
SetTile(96, 3, 2, 0)
SetTile(112, 0, 3, 0)
SetTile(128, 1, 3, 0)
SetTile(16, 2, 3, 0)
SetTile(32, 3, 3, 0)'
expect_lines "twokeeps units" "$M/twokeeps.sms.gz" '^(unit = CreateUnit|SetResourcesHeld)\(' \
'unit = CreateUnit("unit-gold-mine", 15, {1, 2})
SetResourcesHeld(unit, 15000)'

emit_ctrf "wargus-pud-oracle" "$passed" "$failed"
exit $?
